create table if not exists public.brands (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null,
  org_id bigint not null default 1
);
create table if not exists public.retailers (
  id bigint generated by default as identity primary key,
  name text not null,
  channel text not null default 'Grocery',
  region text not null default 'Global',
  total_stores integer not null default 100,
  org_id bigint not null default 1
);
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  brand_id bigint references public.brands(id) on delete cascade,
  name text not null,
  category text not null,
  org_id bigint not null default 1
);
create table if not exists public.sales_facts (
  id bigint generated by default as identity primary key,
  product_id bigint references public.products(id) on delete cascade,
  retailer_id bigint references public.retailers(id) on delete cascade,
  week_ending date not null,
  dollar_sales numeric not null default 0,
  units numeric not null default 0,
  acv_distribution numeric,
  on_promo boolean not null default false,
  promo_type text,
  discount_depth_pct numeric not null default 0,
  org_id bigint not null default 1
);
create table if not exists public.insight_feedback (
  id bigint generated by default as identity primary key,
  analysis_id text,
  user_id uuid references auth.users(id) on delete set null,
  insight_summary text,
  feedback_type text,
  outcome text check (outcome in ('worked','didnt_work','unknown')),
  comment text,
  created_at timestamptz not null default now(),
  org_id bigint not null default 1
);
create table if not exists public.alerts (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade,
  brand_id bigint references public.brands(id) on delete cascade,
  retailer_id bigint references public.retailers(id) on delete cascade,
  category text not null default 'General',
  region text,
  alert_type text not null default 'velocity_swing_down',
  week_ending date not null default current_date,
  baseline_units numeric,
  actual_units numeric,
  swing_pct numeric,
  title text,
  description text,
  narrative text,
  severity text not null default 'info',
  status text not null default 'open',
  related_entity_id text,
  created_at timestamptz not null default now(),
  org_id bigint not null default 1,
  unique (brand_id, retailer_id, week_ending, alert_type)
);

