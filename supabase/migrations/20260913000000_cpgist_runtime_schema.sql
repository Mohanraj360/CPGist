create or replace view public.v_brand_share with (security_invoker = true) as
with brand_week as (
  select b.id as brand_id, b.name as brand_name, b.category, sf.retailer_id, sf.week_ending,
    sum(sf.dollar_sales) as brand_dollar_sales
  from public.sales_facts sf join public.products p on p.id = sf.product_id join public.brands b on b.id = p.brand_id
  group by b.id, b.name, b.category, sf.retailer_id, sf.week_ending
), category_week as (
  select b.category, sf.retailer_id, sf.week_ending, sum(sf.dollar_sales) as category_dollar_sales
  from public.sales_facts sf join public.products p on p.id = sf.product_id join public.brands b on b.id = p.brand_id
  group by b.category, sf.retailer_id, sf.week_ending
)
select bw.brand_id, bw.brand_name, bw.category, bw.retailer_id, r.name as retailer_name, r.channel, r.region,
  bw.week_ending, bw.brand_dollar_sales, cw.category_dollar_sales,
  case when cw.category_dollar_sales > 0 then round((bw.brand_dollar_sales / cw.category_dollar_sales) * 100, 2) end as brand_share_pct
from brand_week bw join category_week cw using (category, retailer_id, week_ending) join public.retailers r on r.id = bw.retailer_id;

create or replace view public.v_promo_lift with (security_invoker = true) as
with base as (
  select sf.*, avg(case when not sf.on_promo then sf.units end) over (partition by sf.product_id, sf.retailer_id order by sf.week_ending rows between 4 preceding and 1 preceding) as trailing_nonpromo_baseline_units
  from public.sales_facts sf
)
select b.product_id, p.name as product_name, p.brand_id, br.name as brand_name, b.retailer_id, r.name as retailer_name,
  r.channel, r.region, b.week_ending, b.promo_type, b.discount_depth_pct, b.units as promo_week_units,
  b.trailing_nonpromo_baseline_units,
  case when b.trailing_nonpromo_baseline_units > 0 then round(((b.units - b.trailing_nonpromo_baseline_units) / b.trailing_nonpromo_baseline_units) * 100, 1) end as pct_lift,
  p.category
from base b join public.products p on p.id = b.product_id join public.brands br on br.id = p.brand_id join public.retailers r on r.id = b.retailer_id
where b.on_promo = true;

